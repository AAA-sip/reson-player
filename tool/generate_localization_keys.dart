// Generates typed localization accessors from bundled English strings.
//
// Usage: dart run tool/generate_localization_keys.dart
// Output: lib/core/localization/strings.g.dart
//
// Usage in code:
//   Text(Strings.settings.title)

import 'dart:convert';
import 'dart:io';

const inputPath = 'assets/local/en.json';
const outputPath = 'lib/core/localization/strings.g.dart';

const _reservedWords = <String>{
  'abstract',
  'as',
  'assert',
  'async',
  'await',
  'base',
  'break',
  'case',
  'catch',
  'class',
  'const',
  'continue',
  'covariant',
  'default',
  'deferred',
  'do',
  'dynamic',
  'else',
  'enum',
  'export',
  'extends',
  'extension',
  'external',
  'factory',
  'false',
  'final',
  'finally',
  'for',
  'function',
  'get',
  'hide',
  'if',
  'implements',
  'import',
  'in',
  'interface',
  'is',
  'late',
  'library',
  'mixin',
  'new',
  'null',
  'on',
  'operator',
  'part',
  'required',
  'rethrow',
  'return',
  'sealed',
  'set',
  'show',
  'static',
  'super',
  'switch',
  'sync',
  'this',
  'throw',
  'true',
  'try',
  'typedef',
  'var',
  'void',
  'when',
  'while',
  'with',
  'yield',
};

void main() {
  final source = File(inputPath);
  if (!source.existsSync()) {
    stderr.writeln('Input file not found: $inputPath');
    exitCode = 1;
    return;
  }

  final json = jsonDecode(source.readAsStringSync()) as Map<String, dynamic>;
  final buffer = StringBuffer(
    '// GENERATED CODE - DO NOT MODIFY BY HAND\n'
    '// Generated by tool/generate_localization_keys.dart from $inputPath\n\n'
    "import 'package:easy_localization/easy_localization.dart';\n\n"
    '/// Typed accessors for localization keys.\n'
    'abstract final class Strings {\n'
    '  Strings._();\n',
  );

  for (final entry in json.entries) {
    if (entry.value is Map<String, dynamic>) {
      buffer.writeln(
        '  static ${_classNameOf([entry.key])} get ${_field(entry.key)} '
        '=> const ${_classNameOf([entry.key])}();',
      );
    } else {
      buffer.writeln('  String get ${_getter(entry.key)} => \'${entry.key}\'.tr();');
    }
  }
  buffer.writeln('}');

  for (final entry in json.entries) {
    if (entry.value is Map<String, dynamic>) {
      _writeNode(buffer, [entry.key], entry.value as Map<String, dynamic>);
    }
  }

  final generated = buffer.toString();
  final outFile = File(outputPath);
  if (outFile.existsSync() && outFile.readAsStringSync() == generated) {
    stdout.writeln('$outputPath is up to date');
    return;
  }
  outFile.writeAsStringSync(generated);
  stdout.writeln('Generated $outputPath');
}

void _writeNode(StringBuffer buffer, List<String> path, Map<String, dynamic> node) {
  final className = _classNameOf(path);
  final dotPath = path.join('.');

  buffer
    ..writeln()
    ..writeln('/// Section `$dotPath.*`.')
    ..writeln('final class $className {')
    ..writeln('  const $className();');

  for (final entry in node.entries) {
    if (entry.value is Map<String, dynamic>) {
      buffer.writeln(
        '  static ${_classNameOf([...path, entry.key])} get ${_field(entry.key)} '
        '=> const ${_classNameOf([...path, entry.key])}();',
      );
    } else {
      buffer.writeln('  String get ${_getter(entry.key)} => \'$dotPath.${entry.key}\'.tr();');
    }
  }
  buffer.writeln('}');

  for (final entry in node.entries) {
    if (entry.value is Map<String, dynamic>) {
      _writeNode(buffer, [...path, entry.key], entry.value as Map<String, dynamic>);
    }
  }
}

String _classNameOf(List<String> path) => '${path.map((segment) => _pascalSegment(segment)).join()}Strings';

String _pascalSegment(String segment) => segment
    .split(RegExp(r'[_.\-]'))
    .where((part) => part.isNotEmpty)
    .map((part) => part[0].toUpperCase() + part.substring(1))
    .join();

String _field(String key) {
  final pascal = _pascalSegment(key);
  return pascal[0].toLowerCase() + pascal.substring(1);
}

String _getter(String key) {
  var name = _field(key);
  if (_reservedWords.contains(name)) name = '${name}Value';
  return name;
}
